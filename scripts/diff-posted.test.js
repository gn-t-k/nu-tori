// scripts/diff-posted を、gh を書いた本文を返すだけの偽物に差し替えて走らせる
"use strict";

const assert = require("node:assert/strict");
const { spawnSync } = require("node:child_process");
const { chmodSync, mkdtempSync, readFileSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join } = require("node:path");
const { describe, it, before, after } = require("node:test");

// 偽の gh は、FAKE_BODY を本文として返し、読んだ API のパスを FAKE_LOG に書く
const FAKE_GH = `#!/usr/bin/env bash
echo "$2" > "$FAKE_LOG"
printf '%s\\n' "$FAKE_BODY"
`;

// 元の本文をファイルに置き、偽の gh で diff-posted を走らせて、結果と読んだパスと後で消すフォルダを返す
const run = ({ original, posted, apiPath }) => {
  const dir = mkdtempSync(join(tmpdir(), "diff-posted-"));
  writeFileSync(join(dir, "gh"), FAKE_GH);
  chmodSync(join(dir, "gh"), 0o755);
  writeFileSync(join(dir, "original.md"), original);
  const log = join(dir, "log");
  writeFileSync(log, "");
  const result = spawnSync(join(__dirname, "diff-posted"), [join(dir, "original.md"), apiPath], {
    encoding: "utf8",
    env: { ...process.env, PATH: `${dir}:${process.env.PATH}`, FAKE_BODY: posted, FAKE_LOG: log },
  });
  return { dir, result, readPath: readFileSync(log, "utf8").trim() };
};

describe("書いた本文を元の本文と比べること", () => {
  describe("同じとき", () => {
    let dir;
    let result;
    before(() => {
      ({ dir, result } = run({ original: "## 題\n\n本文\n", posted: "## 題\n\n本文", apiPath: "issues/1" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("同じと出して 0 で終わること", () => {
      assert.deepEqual([result.status, result.stdout], [0, "同じ\n"]);
    });
  });

  describe("書いたほうにだけ、末尾の署名と空行、行末の空白、CR があるとき", () => {
    let dir;
    let result;
    before(() => {
      const posted = "## 題  \r\n\r\n本文\r\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n";
      ({ dir, result } = run({ original: "## 題\n\n本文\n", posted, apiPath: "issues/comments/5" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("同じとみなすこと", () => {
      assert.equal(result.status, 0);
    });
  });

  describe("PR の署名とセッションの URL が末尾にあるとき", () => {
    let dir;
    let result;
    before(() => {
      const posted = "本文\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_01abc\n";
      ({ dir, result } = run({ original: "本文\n", posted, apiPath: "pulls/3" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("同じとみなすこと", () => {
      assert.equal(result.status, 0);
    });
  });

  // バッククォートが引用符に変わる崩れ（docs/agents/git.md の「クラウドのセッションで GitHub を操作する」）
  describe("書いたほうで書式が崩れたとき", () => {
    let dir;
    let result;
    before(() => {
      ({ dir, result } = run({ original: "`scripts/check` を回す\n", posted: "'scripts/check' を回す", apiPath: "issues/1" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("1 で終わること", () => {
      assert.equal(result.status, 1);
    });

    it("崩れた行を差分に出すこと", () => {
      assert.match(result.stdout, /^\+'scripts\/check' を回す$/m);
    });
  });

  describe("API のパスにリポジトリを付けないとき", () => {
    let dir;
    let readPath;
    before(() => {
      ({ dir, readPath } = run({ original: "本文\n", posted: "本文", apiPath: "pulls/3" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("gn-t-k/nu-tori を読むこと", () => {
      assert.equal(readPath, "repos/gn-t-k/nu-tori/pulls/3");
    });
  });

  describe("API のパスにリポジトリを付けたとき", () => {
    let dir;
    let readPath;
    before(() => {
      ({ dir, readPath } = run({ original: "本文\n", posted: "本文", apiPath: "repos/gn-t-k/nu-tori-ops/issues/2" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("そのリポジトリを読むこと", () => {
      assert.equal(readPath, "repos/gn-t-k/nu-tori-ops/issues/2");
    });
  });

  describe("API のパスが読める形でないとき", () => {
    let dir;
    let result;
    let readPath;
    before(() => {
      ({ dir, result, readPath } = run({ original: "本文\n", posted: "本文", apiPath: "issues/1/comments" }));
    });
    after(() => rmSync(dir, { recursive: true, force: true }));

    it("使い方を出して 2 で終わること", () => {
      assert.deepEqual([result.status, /^使い方: /.test(result.stderr)], [2, true]);
    });

    it("GitHub を読まないこと", () => {
      assert.equal(readPath, "");
    });
  });
});
