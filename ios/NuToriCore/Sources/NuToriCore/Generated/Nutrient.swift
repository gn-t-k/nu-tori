/// 栄養の項目。rawValue は JSON のキー（サーバーの名前。単位を含む）
public enum Nutrient: String, CaseIterable, Sendable, Hashable {
    case biotinUg = "biotin_ug"
    case calciumMg = "calcium_mg"
    case carbohydrateG = "carbohydrate_g"
    case cholesterolMg = "cholesterol_mg"
    case chromiumUg = "chromium_ug"
    case copperMg = "copper_mg"
    case energyKcal = "energy_kcal"
    case fatG = "fat_g"
    case fiberG = "fiber_g"
    case folateUg = "folate_ug"
    case iodineUg = "iodine_ug"
    case ironMg = "iron_mg"
    case magnesiumMg = "magnesium_mg"
    case manganeseMg = "manganese_mg"
    case molybdenumUg = "molybdenum_ug"
    case niacinMg = "niacin_mg"
    case pantothenicAcidMg = "pantothenic_acid_mg"
    case phosphorusMg = "phosphorus_mg"
    case potassiumMg = "potassium_mg"
    case proteinG = "protein_g"
    case saltEquivalentG = "salt_equivalent_g"
    case seleniumUg = "selenium_ug"
    case vitaminAUg = "vitamin_a_ug"
    case vitaminB12Ug = "vitamin_b12_ug"
    case vitaminB1Mg = "vitamin_b1_mg"
    case vitaminB2Mg = "vitamin_b2_mg"
    case vitaminB6Mg = "vitamin_b6_mg"
    case vitaminCMg = "vitamin_c_mg"
    case vitaminDUg = "vitamin_d_ug"
    case vitaminEMg = "vitamin_e_mg"
    case vitaminKUg = "vitamin_k_ug"
    case waterG = "water_g"
    case zincMg = "zinc_mg"

    /// 名前に含まれる単位の表記（`kcal`・`g`・`mg`・`µg`）
    public var unit: String {
        switch self {
        case .biotinUg: "µg"
        case .calciumMg: "mg"
        case .carbohydrateG: "g"
        case .cholesterolMg: "mg"
        case .chromiumUg: "µg"
        case .copperMg: "mg"
        case .energyKcal: "kcal"
        case .fatG: "g"
        case .fiberG: "g"
        case .folateUg: "µg"
        case .iodineUg: "µg"
        case .ironMg: "mg"
        case .magnesiumMg: "mg"
        case .manganeseMg: "mg"
        case .molybdenumUg: "µg"
        case .niacinMg: "mg"
        case .pantothenicAcidMg: "mg"
        case .phosphorusMg: "mg"
        case .potassiumMg: "mg"
        case .proteinG: "g"
        case .saltEquivalentG: "g"
        case .seleniumUg: "µg"
        case .vitaminAUg: "µg"
        case .vitaminB12Ug: "µg"
        case .vitaminB1Mg: "mg"
        case .vitaminB2Mg: "mg"
        case .vitaminB6Mg: "mg"
        case .vitaminCMg: "mg"
        case .vitaminDUg: "µg"
        case .vitaminEMg: "mg"
        case .vitaminKUg: "µg"
        case .waterG: "g"
        case .zincMg: "mg"
        }
    }
}
